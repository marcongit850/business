#!/usr/bin/env python3
"""Build src/pwa-icons.js from the network logos in assets/networks.

Round seals get a navy margin so the ring is not clipped. The builders tile
already fills a navy square and its artwork sits inside the maskable safe zone,
so that maskable icon uses the same scale as the any-purpose icon.
"""

import base64
import io
import os

from PIL import Image

NAVY = (0, 24, 64, 255)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = {
    "business": "assets/networks/walton-county-business-leaders-logo.png",
    "builders": "assets/networks/walton-county-builders-network-logo.jpg",
    "tourism": "assets/networks/walton-county-tourism-network-logo.webp",
}


def render(logo, size, scale):
    canvas = Image.new("RGBA", (size, size), NAVY)
    fitted = logo.convert("RGBA")
    side = max(1, int(round(size * scale)))
    fitted.thumbnail((side, side), Image.Resampling.LANCZOS)
    canvas.alpha_composite(fitted, ((size - fitted.width) // 2, (size - fitted.height) // 2))
    return canvas.convert("RGB")


def png_b64(logo, size, scale):
    buf = io.BytesIO()
    render(logo, size, scale).save(buf, format="PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def main():
    icons = {}
    for network, src in SOURCES.items():
        logo = Image.open(os.path.join(ROOT, src))
        any_scale = 1.0 if network == "builders" else 0.92
        mask_scale = 1.0 if network == "builders" else 0.76
        icons[f"/pwa/{network}-192.png"] = png_b64(logo, 192, any_scale)
        icons[f"/pwa/{network}-512.png"] = png_b64(logo, 512, any_scale)
        icons[f"/pwa/{network}-180.png"] = png_b64(logo, 180, any_scale)
        icons[f"/pwa/{network}-maskable-512.png"] = png_b64(logo, 512, mask_scale)
    out = [
        "// Generated by scripts/build-pwa-icons.py from each network logo.",
        "// Do not edit by hand. Run: python3 scripts/build-pwa-icons.py",
        "export const PWA_ICONS = {",
    ]
    for path in sorted(icons):
        out.append(f'  "{path}": "{icons[path]}",')
    out.append("};")
    out.append("")
    dest = os.path.join(ROOT, "src/pwa-icons.js")
    with open(dest, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
